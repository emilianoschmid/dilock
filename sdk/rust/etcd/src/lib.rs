const METADATA_PREFIX: &str = "/dilock/namespaces/";
const LOCK_PREFIX: &str = "/dilock/locks/";

struct Inner {
    endpoint: String,
    // Cloned etcd Clients share the same tonic channel. Each RPC gets a clone
    // so queued locks and keepalive streams do not serialize on a mutex.
    client: OnceCell<Client>,
    namespace: String,
    epoch: String,
    cleanups: Mutex<Vec<JoinHandle<()>>>,
}

/// One endpoint and deployment-epoch selection. Cloning shares configuration,
/// not a server-side lease or an in-process lock.
#[derive(Clone)]
pub struct EtcdProvider {
    inner: Arc<Inner>,
}

/// Result of the explicit metadata provisioning operation.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MetadataProvision {
    /// This call created the absent metadata key with create-if-absent.
    Created,
    /// A pre-existing key exactly matches this provider's profile and epoch.
    AlreadyCompatible,
}

impl EtcdProvider {
    /// Creates a provider without contacting etcd.
    ///
    /// `epoch` must identify a stable etcd cluster incarnation and must be
    /// shared by clients and the protected resource. It is never generated by
    /// this SDK. Network calls use the per-operation timeout supplied in
    /// [`Options`], except cleanup which has its own fixed bounded budget.
    /// Direct `https://` endpoints return [`Error::UnsupportedCapability`];
    /// place a trusted transport proxy in front of etcd when TLS is required.
    pub fn new(
        endpoint: impl Into<String>,
        namespace: impl Into<String>,
        epoch: impl Into<String>,
    ) -> Result<Self, Error> {
        let endpoint = endpoint.into();
        let namespace = namespace.into();
        let epoch = epoch.into();
        resource_id(&namespace, "validation")?;
        if endpoint.is_empty()
            || endpoint.bytes().any(|b| b == 0)
            || epoch.is_empty()
            || epoch.len() > 1024
            || epoch.bytes().any(|b| b == 0)
        {
            return Err(Error::InvalidConfiguration);
        }
        if endpoint
            .get(.."https://".len())
            .is_some_and(|scheme| scheme.eq_ignore_ascii_case("https://"))
        {
            return Err(Error::UnsupportedCapability);
        }
        Ok(Self {
            inner: Arc::new(Inner {
                endpoint,
                client: OnceCell::new(),
                namespace,
                epoch,
                cleanups: Mutex::new(Vec::new()),
            }),
        })
    }

    /// Returns a reusable resource handle without network activity.
    pub fn lock(&self, resource: &str) -> Result<EtcdHandle, IdentityError> {
        let id = resource_id(&self.inner.namespace, resource)?;
        Ok(EtcdHandle {
            inner: self.inner.clone(),
            name: format!("{LOCK_PREFIX}{id}").into_bytes(),
        })
    }

    /// Explicitly provisions draft 1 namespace metadata using a transaction
    /// that compares version zero. It never overwrites an existing key.
    /// Normal acquisition only reads and validates metadata.
    pub async fn provision_namespace(&self, timeout: Duration) -> Result<MetadataProvision, Error> {
        let key = metadata_key(&self.inner.namespace);
        let value = serde_json::to_vec(&json!({
            "protocol_major": 1,
            "identity_scheme": "sha256-framed-utf8-v1",
            "profile": "etcd-native-lock-v1",
            "coordination_epoch": self.inner.epoch,
            "fixed_lease_ms": Value::Null,
        }))
        .map_err(|_| Error::InvalidConfiguration)?;
        let mut client = self.inner.client(timeout).await?;
        let response = time::timeout(
            timeout,
            client.txn(
                Txn::new()
                    .when(vec![Compare::version(key.clone(), CompareOp::Equal, 0)])
                    .and_then(vec![TxnOp::put(key.clone(), value, None)]),
            ),
        )
        .await
        .map_err(|_| Error::BackendUnavailable("metadata transaction timed out".into()))?
        .map_err(backend_error)?;
        if response.succeeded() {
            return Ok(MetadataProvision::Created);
        }
        self.validate_metadata(timeout).await?;
        Ok(MetadataProvision::AlreadyCompatible)
    }

    /// Waits for scheduled best-effort cleanup tasks. This does not release
    /// leases that are still held by callers.
    pub async fn wait_for_cleanup(&self) {
        let tasks = {
            let mut guard = self.inner.cleanups.lock().expect("cleanup mutex poisoned");
            std::mem::take(&mut *guard)
        };
        for task in tasks {
            let _ = task.await;
        }
    }

    /// Queries the endpoint's etcd server version for diagnostics.
    pub async fn server_version(&self, timeout: Duration) -> Result<String, Error> {
        let mut client = self.inner.client(timeout).await?;
        let response = time::timeout(timeout, client.status())
            .await
            .map_err(|_| Error::BackendUnavailable("etcd status timed out".into()))?
            .map_err(backend_error)?;
        Ok(response.version().to_owned())
    }

    async fn validate_metadata(&self, timeout: Duration) -> Result<(), Error> {
        validate_metadata(&self.inner, timeout).await
    }
}

/// Reusable native Lock name. Only an etcd RPC deadline followed by a
/// confirmed lease revoke can establish a finite wait timeout; no ordinary
/// contention response exists in the native API.
#[derive(Clone)]
pub struct EtcdHandle {
    inner: Arc<Inner>,
    name: Vec<u8>,
}

impl EtcdHandle {
    /// Acquires using the shared default policy (five-second wait and
    /// [`Options::default`] lease settings).
    ///
    /// This delegates to [`Self::acquire`]. It does not create a provider or
    /// connection manager; each attempt still receives its own etcd lease.
    pub async fn acquire_default(&self) -> Result<EtcdLease, Error> {
        self.acquire(DEFAULT_WAIT, Options::default()).await
    }

    /// Acquires using the shared default policy, runs `operation` once, and
    /// awaits native Unlock and revoke before returning.
    ///
    /// The callback can inspect the lease and its fencing revision. Its error
    /// is preserved in [`WithLeaseError::Work`] with the release observation.
    /// Cancelling this helper drops the lease and schedules the adapter's
    /// existing bounded tracked revoke cleanup.
    pub async fn with_lease<F, T, E>(
        &self,
        operation: F,
    ) -> Result<WithLeaseOutput<T>, WithLeaseError<E>>
    where
        F: AsyncFnOnce(&mut EtcdLease) -> Result<T, E>,
    {
        self.with_lease_with(DEFAULT_WAIT, Options::default(), operation)
            .await
    }

    /// Like [`Self::with_lease`], using a complete wait and lease policy.
    ///
    /// The `Options` value is used in full. Use struct update syntax to change
    /// a field while retaining the other documented defaults.
    pub async fn with_lease_with<F, T, E>(
        &self,
        wait: Duration,
        options: Options,
        operation: F,
    ) -> Result<WithLeaseOutput<T>, WithLeaseError<E>>
    where
        F: AsyncFnOnce(&mut EtcdLease) -> Result<T, E>,
    {
        let mut lease = self
            .acquire(wait, options)
            .await
            .map_err(WithLeaseError::Acquire)?;
        let result = operation(&mut lease).await;
        let release = lease.release().await;
        finish_scope(result, release)
    }

    /// Returns `UnsupportedCapability`: etcd's native Lock service has no
    /// try-lock RPC, and a timed-out waiter is not confirmed contention.
    pub async fn try_acquire(&self, options: Options) -> Result<Option<EtcdLease>, Error> {
        options.validate()?;
        Err(Error::UnsupportedCapability)
    }

    /// Waits up to `wait` for etcd's native FIFO Lock queue. Every invocation
    /// receives a new server lease and runs keepalive while waiting. The
    /// deadline includes metadata, grant, Lock and ownership verification.
    /// Cancellation drops the attempt guard, stops keepalive and schedules a
    /// bounded revoke; because the RPC may have reached etcd, cancellation has
    /// an unknown remote outcome until that cleanup is confirmed.
    pub async fn acquire(&self, wait: Duration, options: Options) -> Result<EtcdLease, Error> {
        validate_wait(wait)?;
        let end = Instant::now()
            .checked_add(wait)
            .ok_or(dilock::OptionError::InvalidWait)?;
        self.acquire_until(options, Some(end)).await
    }

    async fn acquire_until(
        &self,
        options: Options,
        end: Option<Instant>,
    ) -> Result<EtcdLease, Error> {
        let options = options.validate()?;
        let end = end.ok_or(Error::WaitTimeout)?;
        let first_remaining = remaining(end)?;
        let metadata_budget = std::cmp::min(options.rpc_timeout, first_remaining);
        match time::timeout(
            metadata_budget,
            self.inner.provider_validate_metadata(metadata_budget),
        )
        .await
        {
            Ok(result) => result?,
            Err(_) if remaining(end).is_err() => return Err(Error::WaitTimeout),
            Err(_) => {
                return Err(Error::BackendUnavailable(
                    "metadata validation timed out".into(),
                ));
            }
        }

        let budget = std::cmp::min(options.rpc_timeout, remaining(end)?);
        let mut client = self.inner.client(budget).await?;
        let requested_ttl = options
            .lease
            .as_secs()
            .saturating_add(u64::from(options.lease.subsec_nanos() != 0));
        if requested_ttl == 0 || requested_ttl > i64::MAX as u64 {
            return Err(Error::InvalidArgument(dilock::OptionError::InvalidLease));
        }
        let grant_started = Instant::now();
        let granted = time::timeout(
            std::cmp::min(options.rpc_timeout, remaining(end)?),
            client.lease_grant(requested_ttl as i64, None),
        )
        .await
        .map_err(|_| Error::AcquisitionUnknown)?
        .map_err(backend_error)?;
        if granted.id() <= 0 || granted.ttl() <= 0 {
            return Err(Error::AcquisitionUnknown);
        }
        let lease_id = granted.id();
        let effective_ttl = Duration::from_secs(granted.ttl() as u64);
        let health = Arc::new(Mutex::new(LeaseHealth {
            deadline: conservative_deadline(grant_started, effective_ttl),
            lost: false,
        }));
        let (stop_tx, stop_rx) = oneshot::channel();
        let keepalive = tokio::spawn(keepalive_loop(
            client.clone(),
            lease_id,
            effective_ttl,
            options.rpc_timeout,
            health.clone(),
            stop_rx,
        ));
        let mut attempt = AttemptGuard::new(
            self.inner.clone(),
            lease_id,
            Some(stop_tx),
            keepalive,
            options.cleanup_timeout,
        );

        let mut lock_client = client.clone();
        let lock_remaining = match remaining(end) {
            Ok(value) => value,
            Err(_) => {
                return if attempt.revoke_now().await {
                    Err(Error::WaitTimeout)
                } else {
                    Err(Error::AcquisitionUnknown)
                };
            }
        };
        let response = match time::timeout(
            lock_remaining,
            lock_client.lock(
                self.name.clone(),
                Some(LockOptions::new().with_lease(lease_id)),
            ),
        )
        .await
        {
            Ok(Ok(response)) => response,
            Ok(Err(error)) => {
                let wait_expired = remaining(end).is_err();
                return if attempt.revoke_now().await {
                    if wait_expired {
                        Err(Error::WaitTimeout)
                    } else {
                        Err(backend_error(error))
                    }
                } else {
                    Err(Error::AcquisitionUnknown)
                };
            }
            Err(_) => {
                return if attempt.revoke_now().await {
                    Err(Error::WaitTimeout)
                } else {
                    Err(Error::AcquisitionUnknown)
                };
            }
        };
        let key = response.key().to_vec();
        if key.is_empty() {
            return if attempt.revoke_now().await {
                Err(Error::ProtocolMismatch)
            } else {
                Err(Error::AcquisitionUnknown)
            };
        }

        // This clone is an independent mutable RPC handle over the shared
        // provider channel; keepalive continues concurrently.
        let mut verify_client = client.clone();
        let wait_remaining = match remaining(end) {
            Ok(remaining) => remaining,
            Err(_) => {
                return if attempt.revoke_now().await {
                    Err(Error::WaitTimeout)
                } else {
                    Err(Error::AcquisitionUnknown)
                };
            }
        };
        let verify_remaining = std::cmp::min(
            options.rpc_timeout,
            health_remaining(&health).min(wait_remaining),
        );
        if verify_remaining.is_zero() {
            return if attempt.revoke_now().await {
                Err(Error::WaitTimeout)
            } else {
                Err(Error::AcquisitionUnknown)
            };
        }
        let verified = time::timeout(
            verify_remaining,
            verify_client.get(key.clone(), Some(GetOptions::new().with_limit(1))),
        )
        .await;
        let verified = match verified {
            Ok(Ok(value)) => value,
            Ok(Err(error)) => {
                return if attempt.revoke_now().await {
                    Err(backend_error(error))
                } else {
                    Err(Error::AcquisitionUnknown)
                };
            }
            Err(_) => {
                return if attempt.revoke_now().await {
                    Err(verification_timeout_error(end, &health))
                } else {
                    Err(Error::AcquisitionUnknown)
                };
            }
        };
        let kv = verified.kvs().first();
        let Some(kv) = kv.filter(|kv| kv.key() == key && kv.lease() == lease_id) else {
            return if attempt.revoke_now().await {
                Err(Error::ProtocolMismatch)
            } else {
                Err(Error::AcquisitionUnknown)
            };
        };
        let revision = kv.create_revision();
        if revision <= 0 || health_remaining(&health).is_zero() {
            return if attempt.revoke_now().await {
                Err(Error::LeaseLost)
            } else {
                Err(Error::AcquisitionUnknown)
            };
        }
        let fence = EtcdFence {
            epoch: self.inner.epoch.clone(),
            revision: revision as u64,
        };
        if !options.auto_renew {
            attempt.stop_keepalive().await;
            if health_remaining(&health).is_zero() {
                return if attempt.revoke_now().await {
                    Err(Error::LeaseLost)
                } else {
                    Err(Error::AcquisitionUnknown)
                };
            }
        }
        let (stop, keepalive_task) = attempt.disarm();
        Ok(EtcdLease {
            inner: self.inner.clone(),
            key,
            lease_id,
            options,
            ttl: effective_ttl,
            health,
            fence,
            stop,
            keepalive_task,
            state: LeaseState::Held,
            release_outcome: None,
        })
    }
}

impl Inner {
    async fn client(&self, timeout: Duration) -> Result<Client, Error> {
        time::timeout(
            timeout,
            self.client
                .get_or_try_init(|| async { connect(&self.endpoint, timeout).await }),
        )
        .await
        .map_err(|_| Error::BackendUnavailable("etcd connection timed out".into()))?
        .cloned()
    }

    async fn provider_validate_metadata(&self, timeout: Duration) -> Result<(), Error> {
        validate_metadata(self, timeout).await
    }
}

async fn validate_metadata(inner: &Inner, timeout: Duration) -> Result<(), Error> {
    let mut client = inner.client(timeout).await?;
    let response = time::timeout(
        timeout,
        client.get(
            metadata_key(&inner.namespace),
            Some(GetOptions::new().with_limit(1)),
        ),
    )
    .await
    .map_err(|_| Error::BackendUnavailable("metadata range timed out".into()))?
    .map_err(backend_error)?;
    let Some(kv) = response.kvs().first() else {
        return Err(Error::ProtocolMismatch);
    };
    if kv.value().len() > 8192 {
        return Err(Error::ProtocolMismatch);
    }
    let value: Value = serde_json::from_slice(kv.value()).map_err(|_| Error::ProtocolMismatch)?;
    let object = value.as_object().ok_or(Error::ProtocolMismatch)?;
    if has_duplicate_top_level_fields(kv.value()) {
        return Err(Error::ProtocolMismatch);
    }
    let expected = [
        ("protocol_major", Value::from(1)),
        ("identity_scheme", Value::from("sha256-framed-utf8-v1")),
        ("profile", Value::from("etcd-native-lock-v1")),
        ("coordination_epoch", Value::from(inner.epoch.clone())),
        ("fixed_lease_ms", Value::Null),
    ];
    if expected
        .iter()
        .any(|(name, want)| object.get(*name) != Some(want))
    {
        return Err(Error::ProtocolMismatch);
    }
    Ok(())
}

fn has_duplicate_top_level_fields(raw: &[u8]) -> bool {
    struct DuplicateFlag(bool);

    impl<'de> Deserialize<'de> for DuplicateFlag {
        fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
        where
            D: Deserializer<'de>,
        {
            struct FieldsVisitor;

            impl<'de> Visitor<'de> for FieldsVisitor {
                type Value = bool;

                fn expecting(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
                    formatter.write_str("a JSON object")
                }

                fn visit_map<A>(self, mut map: A) -> Result<Self::Value, A::Error>
                where
                    A: MapAccess<'de>,
                {
                    let mut names = std::collections::HashSet::new();
                    let mut duplicate = false;
                    while let Some(name) = map.next_key::<String>()? {
                        duplicate |= !names.insert(name);
                        map.next_value::<IgnoredAny>()?;
                    }
                    Ok(duplicate)
                }
            }

            deserializer.deserialize_map(FieldsVisitor).map(Self)
        }
    }

    serde_json::from_slice::<DuplicateFlag>(raw)
        .map(|flag| flag.0)
        .unwrap_or(false)
}

fn metadata_key(namespace: &str) -> String {
    format!("{METADATA_PREFIX}{namespace}/meta")
}

fn connect_options(timeout: Duration) -> ConnectOptions {
    // Acquisition/RPC budgets are applied per request with Tokio's timeout.
    // Keep the first caller's policy out of the shared channel.
    ConnectOptions::new().with_connect_timeout(timeout)
}

async fn connect(endpoint: &str, timeout: Duration) -> Result<Client, Error> {
    time::timeout(
        timeout,
        Client::connect([endpoint], Some(connect_options(timeout))),
    )
    .await
    .map_err(|_| Error::BackendUnavailable("etcd connection timed out".into()))?
    .map_err(backend_error)
}

fn remaining(deadline: Instant) -> Result<Duration, Error> {
    let remaining = deadline.saturating_duration_since(Instant::now());
    if remaining.is_zero() {
        Err(Error::WaitTimeout)
    } else {
        Ok(remaining)
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum OwnershipObservation {
    Owned,
    NotOwned,
    Unknown,
}

#[derive(Debug, Clone, PartialEq, Eq)]
struct LeaseHealth {
    deadline: Instant,
    lost: bool,
}

fn health_remaining(health: &Mutex<LeaseHealth>) -> Duration {
    let health = health.lock().expect("lease health mutex poisoned");
    if health.lost {
        Duration::ZERO
    } else {
        health.deadline.saturating_duration_since(Instant::now())
    }
}

fn verification_timeout_error(wait_deadline: Instant, health: &Mutex<LeaseHealth>) -> Error {
    if remaining(wait_deadline).is_err() {
        Error::WaitTimeout
    } else if health_remaining(health).is_zero() {
        Error::LeaseLost
    } else {
        Error::BackendUnavailable("etcd ownership verification timed out".into())
    }
}

fn conservative_deadline(started: Instant, ttl: Duration) -> Instant {
    started + ttl.saturating_sub(std::cmp::max(Duration::from_millis(100), ttl / 10))
}

async fn keepalive_loop(
    mut client: Client,
    lease_id: i64,
    ttl: Duration,
    rpc_timeout: Duration,
    health: Arc<Mutex<LeaseHealth>>,
    mut stop: oneshot::Receiver<()>,
) {
    let result = async {
        let (mut keeper, mut stream) =
            time::timeout(rpc_timeout, client.lease_keep_alive(lease_id))
                .await
                .map_err(|_| Error::LeaseLost)?
                .map_err(backend_error)?;
        // Opening the bidirectional stream is not a keepalive acknowledgement.
        // Preserve the grant's conservative deadline until a response confirms
        // that etcd extended this lease.
        let interval = std::cmp::max(Duration::from_millis(50), ttl / 3);
        loop {
            tokio::select! {
                _ = &mut stop => return Ok::<(), Error>(()),
                _ = time::sleep(interval) => {}
            }
            let sent = Instant::now();
            tokio::select! {
                _ = &mut stop => return Ok(()),
                result = time::timeout(interval, keeper.keep_alive()) => {
                    result.map_err(|_| Error::LeaseLost)?.map_err(backend_error)?;
                }
            }
            let response = tokio::select! {
                _ = &mut stop => return Ok(()),
                result = time::timeout(interval, stream.message()) => {
                    result.map_err(|_| Error::LeaseLost)?.map_err(backend_error)?
                        .ok_or(Error::LeaseLost)?
                }
            };
            if response.id() != lease_id || response.ttl() <= 0 {
                return Err(Error::LeaseLost);
            }
            let new_ttl = Duration::from_secs(response.ttl() as u64);
            if !apply_keepalive_ack(&health, sent, new_ttl) {
                return Err(Error::LeaseLost);
            }
        }
    }
    .await;
    if result.is_err() {
        health.lock().expect("lease health mutex poisoned").lost = true;
    }
}

fn apply_keepalive_ack(health: &Mutex<LeaseHealth>, sent: Instant, ttl: Duration) -> bool {
    let mut state = health.lock().expect("lease health mutex poisoned");
    let now = Instant::now();
    let renewed_deadline = conservative_deadline(sent, ttl);
    if now >= state.deadline || now >= renewed_deadline {
        state.lost = true;
        return false;
    }
    state.deadline = renewed_deadline;
    true
}

/// Fencing identity returned only after exact-key Range verification.
///
/// The revision orders creates only inside `epoch`; snapshot restoration or
/// cluster replacement requires a coordinated fence migration.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EtcdFence {
    /// Stable coordinator-incarnation identifier provisioned in metadata.
    pub epoch: String,
    /// Positive `create_revision` of the verified native lock key.
    pub revision: u64,
}

/// One non-Clone native etcd lock generation.
pub struct EtcdLease {
    inner: Arc<Inner>,
    key: Vec<u8>,
    lease_id: i64,
    options: Options,
    ttl: Duration,
    health: Arc<Mutex<LeaseHealth>>,
    fence: EtcdFence,
    stop: Option<oneshot::Sender<()>>,
    keepalive_task: Option<JoinHandle<()>>,
    state: LeaseState,
    release_outcome: Option<ReleaseOutcome>,
}

impl EtcdLease {
    /// Reads the local conservative state. This is not a remote ownership query
    /// and cannot stop a paused process from continuing work.
    pub fn state(&mut self) -> LeaseState {
        if self.state == LeaseState::Held && health_remaining(&self.health).is_zero() {
            self.state = LeaseState::Lost;
        }
        self.state
    }

    /// Returns the verified epoch/revision pair for resource-side fencing.
    pub fn fence(&self) -> &EtcdFence {
        &self.fence
    }

    /// Server TTL after etcd's integer-second grant rounding.
    pub fn effective_lease_ms(&self) -> u64 {
        self.ttl.as_millis() as u64
    }

    /// Fails when local conservative validity has ended.
    pub fn ensure_held(&mut self) -> Result<(), Error> {
        (self.state() == LeaseState::Held)
            .then_some(())
            .ok_or(Error::LeaseLost)
    }

    /// Confirms exact-key ownership, performs native Unlock, and revokes only
    /// this attempt's distinct lease. `Released` requires both cleanup ACKs;
    /// cancellation cannot cause a later call to repeat an ambiguous RPC.
    /// Dropping the lease schedules bounded revoke cleanup.
    pub async fn release(&mut self) -> ReleaseOutcome {
        if let Some(outcome) = begin_release(&mut self.state, &mut self.release_outcome) {
            return outcome;
        }
        let timeout = self.options.cleanup_timeout;
        let cleanup_deadline = cleanup_deadline(timeout);
        self.stop_keepalive_until(cleanup_deadline).await;
        // etcd's Unlock may acknowledge a no-op after the lease expires. Confirm
        // that this exact opaque key still belongs to this attempt before sending
        // Unlock, then require both cleanup acknowledgements to claim Released.
        let ownership =
            observe_ownership(&self.inner, &self.key, self.lease_id, cleanup_deadline).await;
        let unlock_acknowledged = if ownership == OwnershipObservation::Owned {
            let unlock_result = async {
                let mut client = self
                    .inner
                    .client(remaining_cleanup(cleanup_deadline)?)
                    .await?;
                time::timeout(
                    remaining_cleanup(cleanup_deadline)?,
                    client.unlock(self.key.clone()),
                )
                .await
                .map_err(|_| Error::AcquisitionUnknown)?
                .map_err(backend_error)?;
                Ok::<(), Error>(())
            }
            .await;
            unlock_result.is_ok()
        } else {
            false
        };
        let revoke_result = revoke_until(&self.inner, self.lease_id, cleanup_deadline).await;
        let outcome = classify_release(ownership, unlock_acknowledged, revoke_result.is_ok());
        self.state = if outcome == ReleaseOutcome::Unknown {
            LeaseState::ReleasedUnknown
        } else {
            LeaseState::Released
        };
        self.release_outcome = Some(outcome);
        outcome
    }

    async fn stop_keepalive_until(&mut self, deadline: Instant) {
        if let Some(stop) = self.stop.take() {
            let _ = stop.send(());
        }
        stop_task_until(&mut self.keepalive_task, deadline).await;
    }
}

fn begin_release(
    state: &mut LeaseState,
    outcome: &mut Option<ReleaseOutcome>,
) -> Option<ReleaseOutcome> {
    if let Some(outcome) = *outcome {
        return Some(outcome);
    }
    if matches!(
        state,
        LeaseState::Releasing | LeaseState::Released | LeaseState::ReleasedUnknown
    ) {
        *state = LeaseState::ReleasedUnknown;
        *outcome = Some(ReleaseOutcome::Unknown);
        return Some(ReleaseOutcome::Unknown);
    }
    *state = LeaseState::Releasing;
    *outcome = Some(ReleaseOutcome::Unknown);
    None
}

impl Drop for EtcdLease {
    fn drop(&mut self) {
        if matches!(
            self.state,
            LeaseState::Held
                | LeaseState::Lost
                | LeaseState::Releasing
                | LeaseState::ReleasedUnknown
        ) {
            if let Some(stop) = self.stop.take() {
                let _ = stop.send(());
            }
            schedule_revoke(&self.inner, self.lease_id, self.options.cleanup_timeout);
        }
    }
}

struct AttemptGuard {
    inner: Arc<Inner>,
    lease_id: i64,
    stop: Option<oneshot::Sender<()>>,
    keepalive_task: Option<JoinHandle<()>>,
    timeout: Duration,
    armed: bool,
}

impl AttemptGuard {
    fn new(
        inner: Arc<Inner>,
        lease_id: i64,
        stop: Option<oneshot::Sender<()>>,
        task: JoinHandle<()>,
        timeout: Duration,
    ) -> Self {
        Self {
            inner,
            lease_id,
            stop,
            keepalive_task: Some(task),
            timeout,
            armed: true,
        }
    }

    async fn revoke_now(&mut self) -> bool {
        self.armed = false;
        let deadline = cleanup_deadline(self.timeout);
        if let Some(stop) = self.stop.take() {
            let _ = stop.send(());
        }
        stop_task_until(&mut self.keepalive_task, deadline).await;
        revoke_until(&self.inner, self.lease_id, deadline)
            .await
            .is_ok()
    }

    async fn stop_keepalive(&mut self) {
        let deadline = cleanup_deadline(self.timeout);
        if let Some(stop) = self.stop.take() {
            let _ = stop.send(());
        }
        stop_task_until(&mut self.keepalive_task, deadline).await;
    }

    fn disarm(&mut self) -> (Option<oneshot::Sender<()>>, Option<JoinHandle<()>>) {
        self.armed = false;
        (self.stop.take(), self.keepalive_task.take())
    }
}

impl Drop for AttemptGuard {
    fn drop(&mut self) {
        if self.armed {
            if let Some(stop) = self.stop.take() {
                let _ = stop.send(());
            }
            schedule_revoke(&self.inner, self.lease_id, self.timeout);
        }
    }
}

async fn revoke(inner: &Inner, lease_id: i64, timeout: Duration) -> Result<(), Error> {
    revoke_until(inner, lease_id, cleanup_deadline(timeout)).await
}

async fn revoke_until(inner: &Inner, lease_id: i64, deadline: Instant) -> Result<(), Error> {
    let mut client = inner.client(remaining_cleanup(deadline)?).await?;
    time::timeout(remaining_cleanup(deadline)?, client.lease_revoke(lease_id))
        .await
        .map_err(|_| Error::AcquisitionUnknown)?
        .map(|_| ())
        .map_err(backend_error)
}

fn cleanup_deadline(timeout: Duration) -> Instant {
    Instant::now()
        .checked_add(timeout)
        .expect("Options validates representable cleanup deadlines")
}

fn remaining_cleanup(deadline: Instant) -> Result<Duration, Error> {
    remaining_cleanup_at(deadline, Instant::now())
}

fn remaining_cleanup_at(deadline: Instant, now: Instant) -> Result<Duration, Error> {
    let remaining = deadline.saturating_duration_since(now);
    if remaining.is_zero() {
        Err(Error::AcquisitionUnknown)
    } else {
        Ok(remaining)
    }
}

async fn stop_task_until(task: &mut Option<JoinHandle<()>>, deadline: Instant) {
    if let Some(mut task) = task.take() {
        let remaining = deadline.saturating_duration_since(Instant::now());
        if remaining.is_zero() || time::timeout(remaining, &mut task).await.is_err() {
            task.abort();
            let _ = task.await;
        }
    }
}

fn schedule_revoke(inner: &Arc<Inner>, lease_id: i64, timeout: Duration) {
    let Ok(runtime) = tokio::runtime::Handle::try_current() else {
        return;
    };
    let cleanup_inner = inner.clone();
    let task = runtime.spawn(async move {
        let _ = revoke(&cleanup_inner, lease_id, timeout).await;
    });
    if let Ok(mut tasks) = inner.cleanups.lock() {
        tasks.retain(|task| !task.is_finished());
        tasks.push(task);
    } else {
        task.abort();
    }
}

async fn observe_ownership(
    inner: &Inner,
    key: &[u8],
    lease_id: i64,
    deadline: Instant,
) -> OwnershipObservation {
    let client_timeout = match remaining_cleanup(deadline) {
        Ok(timeout) => timeout,
        Err(_) => return OwnershipObservation::Unknown,
    };
    let mut client = match inner.client(client_timeout).await {
        Ok(client) => client,
        Err(_) => return OwnershipObservation::Unknown,
    };
    let request_timeout = match remaining_cleanup(deadline) {
        Ok(timeout) => timeout,
        Err(_) => return OwnershipObservation::Unknown,
    };
    let response = time::timeout(
        request_timeout,
        client.get(key.to_vec(), Some(GetOptions::new().with_limit(1))),
    )
    .await;
    match response {
        Ok(Ok(response)) => response
            .kvs()
            .first()
            .map(|kv| (kv.key(), kv.lease()))
            .map_or_else(
                || classify_ownership(None, key, lease_id),
                |(observed_key, observed_lease)| {
                    classify_ownership(Some((observed_key, observed_lease)), key, lease_id)
                },
            ),
        Ok(Err(_)) | Err(_) => OwnershipObservation::Unknown,
    }
}

fn classify_ownership(
    observed: Option<(&[u8], i64)>,
    expected_key: &[u8],
    expected_lease_id: i64,
) -> OwnershipObservation {
    match observed {
        Some((key, lease_id)) if key == expected_key && lease_id == expected_lease_id => {
            OwnershipObservation::Owned
        }
        Some(_) | None => OwnershipObservation::NotOwned,
    }
}

fn classify_release(
    ownership: OwnershipObservation,
    unlock_acknowledged: bool,
    revoke_acknowledged: bool,
) -> ReleaseOutcome {
    match ownership {
        OwnershipObservation::NotOwned => ReleaseOutcome::AlreadyNotOwned,
        OwnershipObservation::Unknown => ReleaseOutcome::Unknown,
        OwnershipObservation::Owned if unlock_acknowledged && revoke_acknowledged => {
            ReleaseOutcome::Released
        }
        OwnershipObservation::Owned if revoke_acknowledged => ReleaseOutcome::AlreadyNotOwned,
        OwnershipObservation::Owned => ReleaseOutcome::Unknown,
    }
}

fn backend_error(_: etcd_client::Error) -> Error {
    Error::BackendUnavailable("etcd RPC failed".into())
}

