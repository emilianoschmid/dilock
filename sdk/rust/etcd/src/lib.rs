    #[tokio::test]
    async fn expired_cleanup_deadline_aborts_keepalive_instead_of_detaching_it() {
        struct DropSignal(std::sync::Arc<std::sync::atomic::AtomicBool>);
        impl Drop for DropSignal {
            fn drop(&mut self) {
                self.0.store(true, std::sync::atomic::Ordering::SeqCst);
            }
        }

        let cancelled = std::sync::Arc::new(std::sync::atomic::AtomicBool::new(false));
        let mut task = Some(tokio::spawn({
            let cancelled = cancelled.clone();
            async move {
                let _drop_signal = DropSignal(cancelled);
                std::future::pending::<()>().await;
            }
        }));
        tokio::task::yield_now().await;

        stop_task_until(&mut task, Instant::now()).await;

        assert!(task.is_none());
        assert!(cancelled.load(std::sync::atomic::Ordering::SeqCst));
    }

