//! Native etcd v3 Lock/Lease adapter for Dilock draft 1.
//!
//! Each attempt grants its own etcd lease, even when attempts originate from
//! the same provider. Acquisition uses the native Lock service and verifies
//! the exact returned key with a linearizable Range before returning a lease.
//! The create revision and configured epoch form the fencing token; protected
//! resources must register and compare that pair atomically.

use dilock::{
    DEFAULT_WAIT, Error, IdentityError, LeaseState, Options, ReleaseOutcome, WithLeaseError,
    WithLeaseOutput, resource_id, validate_wait,
};

fn finish_successful_scope<T, E>(
    value: T,
    release: ReleaseOutcome,
) -> Result<WithLeaseOutput<T>, WithLeaseError<E>> {
    if release == ReleaseOutcome::Released {
        Ok(WithLeaseOutput { value, release })
    } else {
        Err(WithLeaseError::Release { outcome: release })
    }
}

fn finish_scope<T, E>(
    result: Result<T, E>,
    release: ReleaseOutcome,
) -> Result<WithLeaseOutput<T>, WithLeaseError<E>> {
    match result {
        Ok(value) => finish_successful_scope(value, release),
        Err(source) => Err(WithLeaseError::Work { source, release }),
    }
}
